def keyinfo(key):
    return "ascii:  <{}>, dec:  <{}>, hex:  [{}]".format(key, ord(key), hex(ord(key)))


def ascinfo(key):
    if key is None:
        return "key is None"

    ordkey = ord(key)
    hexkey = hex(ordkey)
    if ordkey > 255:
        return "non-ascii unicode:  <{}>, dec:  <{}>, hex:  [{}]".format(
            key, ordkey, hexkey
        )

    return "ascii:  <{}>, dec:  <{}>, hex:  [{}]".format(
        ASCIITable[ordkey]["Symbol"], ordkey, hexkey
    )

def ascstr(keys):
    if keys is None:
        logging.debug(f"ascstr keys is None.")
        return None

    asckey_list = []
    for key in keys:
        asckey = ascinfo(key)
        logging.debug(f"ascstr key is <{asckey}.")
        asckey_list.append(asckey)

    logging.debug(f"asckey_list is <{asckey_list}.")
    return asckey_list

def logdebug_ascstr(keys):
    keylist = ascstr(keys)
    keyno = 0
    for key in keylist:
        keyno += 1
        logging.debug(f"Key num {keyno}:  {key}")


